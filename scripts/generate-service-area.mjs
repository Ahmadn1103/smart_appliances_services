    "Louisa", "Lovettsville", "Madison", "Markham", "Marshall", "Maurertown", "Middleburg", "Middletown", "Midland",
    "Milford", "Mineral", "Mitchells", "Montpelier Station", "Montross", "Newington", "Ninde", "Nokesville",
